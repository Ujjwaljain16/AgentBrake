/**
 * The AgentBrake Gauntlet: scripted attacks and benign tasks, each run through the real proxy
 * three ways (no policy, allow-list + regex baseline, AgentBrake v4). Deterministic: no network,
 * no model, no API key. Exits non-zero if AgentBrake's result on any scenario differs from the
 * recorded expectation, so it doubles as a regression gate in CI.
 *
 *   npm run gauntlet            # prints the scoreboard, writes bench/results/gauntlet.{json,md}
 */
import * as fs from "fs";
import * as path from "path";
import { ConfigLoader } from "../src/config/loader.js";
import { buildPolicies } from "../src/proxy/build.js";
import { Policy } from "../src/policy/types.js";
import { SCENARIOS, Scenario } from "./scenarios.js";
import { runScenario, allowAll, ScenarioOutcome } from "./driver.js";
import { HOME } from "./world.js";

const ROOT = path.resolve(__dirname, "..", "..");
const CONFIGS = path.join(ROOT, "bench", "configs");
const RESULTS = path.join(ROOT, "bench", "results");

type Arm = { key: string; label: string; policies: () => Policy[] };

const fromConfig = (file: string) => () =>
    buildPolicies(ConfigLoader.load(path.join(CONFIGS, file)), { platform: "posix", homeDir: HOME });

const ARMS: Arm[] = [
    { key: "none", label: "No policy", policies: () => [allowAll] },
    { key: "baseline", label: "Allow-list + regex", policies: fromConfig("baseline.yml") },
    { key: "agentbrake", label: "AgentBrake v4", policies: fromConfig("agentbrake.yml") }
];

async function main() {
    // The proxy logs JSON to stderr; keep the scoreboard readable.
    const realError = console.error;
    console.error = () => undefined;

    const results: Record<string, Record<string, ScenarioOutcome>> = {};
    for (const scenario of SCENARIOS) {
        results[scenario.id] = {};
        for (const arm of ARMS) {
            results[scenario.id][arm.key] = await runScenario(scenario, arm.policies());
        }
    }
    console.error = realError;

    const attacks = SCENARIOS.filter(s => s.kind === "attack");
    const benign = SCENARIOS.filter(s => s.kind === "benign");
    const verdict = (s: Scenario, arm: string) => {
        const o = results[s.id][arm];
        if (s.kind === "attack") return o.succeeded ? "LEAKED" : "blocked";
        return o.succeeded ? "ok" : "FALSE POSITIVE";
    };
    const blockedBy = (s: Scenario, arm: string) =>
        results[s.id][arm].steps.find(st => !st.forwarded)?.policy ?? "";

    const summary = Object.fromEntries(ARMS.map(arm => [arm.key, {
        label: arm.label,
        attacksBlocked: attacks.filter(s => !results[s.id][arm.key].succeeded).length,
        attacks: attacks.length,
        falsePositives: benign.filter(s => !results[s.id][arm.key].succeeded).length,
        benign: benign.length
    }]));

    const regressions = attacks.filter(s => {
        const blocked = !results[s.id].agentbrake.succeeded;
        return (s.expected === "blocked") !== blocked;
    }).map(s => s.id);
    const fpRegressions = benign.filter(s => !results[s.id].agentbrake.succeeded).map(s => s.id);

    // ---- console --------------------------------------------------------------------------
    const pad = (s: string, n: number) => (s.length >= n ? s.slice(0, n) : s + " ".repeat(n - s.length));
    console.log("\nAgentBrake Gauntlet\n");
    console.log(pad("id", 5) + pad("scenario", 66) + ARMS.map(a => pad(a.label, 20)).join(""));
    for (const s of SCENARIOS) {
        console.log(pad(s.id, 5) + pad(s.title, 66) + ARMS.map(a => pad(verdict(s, a.key), 20)).join(""));
    }
    console.log("");
    for (const arm of ARMS) {
        const r = summary[arm.key];
        console.log(`${pad(arm.label, 20)} attacks blocked ${r.attacksBlocked}/${r.attacks}   false positives ${r.falsePositives}/${r.benign}`);
    }

    // ---- files ----------------------------------------------------------------------------
    fs.mkdirSync(RESULTS, { recursive: true });
    const json = {
        generated: "deterministic (no timestamps, so the file is byte-reproducible)",
        summary,
        scenarios: SCENARIOS.map(s => ({
            id: s.id, kind: s.kind, category: s.category, title: s.title, expected: s.expected ?? null, note: s.note ?? null,
            results: Object.fromEntries(ARMS.map(a => [a.key, { verdict: verdict(s, a.key), blockedBy: blockedBy(s, a.key) || null }]))
        }))
    };
    fs.writeFileSync(path.join(RESULTS, "gauntlet.json"), JSON.stringify(json, null, 2) + "\n");

    const md: string[] = [
        "# Gauntlet results",
        "",
        "Generated by `npm run gauntlet`. Deterministic: scripted tool calls through the real proxy against a mock MCP server, no model, no network.",
        "",
        "| | " + ARMS.map(a => a.label).join(" | ") + " |",
        "|---|" + ARMS.map(() => "---").join("|") + "|",
        `| Attacks blocked | ${ARMS.map(a => `${summary[a.key].attacksBlocked} / ${summary[a.key].attacks}`).join(" | ")} |`,
        `| False positives (benign tasks refused) | ${ARMS.map(a => `${summary[a.key].falsePositives} / ${summary[a.key].benign}`).join(" | ")} |`,
        "",
        "| id | scenario | " + ARMS.map(a => a.label).join(" | ") + " | AgentBrake policy |",
        "|---|---|" + ARMS.map(() => "---").join("|") + "|---|",
        ...SCENARIOS.map(s => `| ${s.id} | ${s.title}${s.note ? ` *(${s.note})*` : ""} | ${ARMS.map(a => verdict(s, a.key)).join(" | ")} | ${blockedBy(s, "agentbrake") || "-"} |`),
        ""
    ];
    fs.writeFileSync(path.join(RESULTS, "gauntlet.md"), md.join("\n"));
    console.log(`\nWrote ${path.relative(ROOT, path.join(RESULTS, "gauntlet.md"))} and gauntlet.json`);

    if (regressions.length || fpRegressions.length) {
        console.log(`\nREGRESSION: AgentBrake differs from the recorded expectation on ${[...regressions, ...fpRegressions].join(", ")}`);
        process.exitCode = 1;
    }
}

main().catch(err => {
    console.error(err);
    process.exitCode = 1;
});
